/** Typed against ErrorCode, so renaming a code fails typecheck instead of leaving a stale name here. */
const ERRORS = [
  [["STALE_WRITE"], "the note changed since you read it; read it again, then retry with the new `updatedAt`."],
  [["LOSSY_REWRITE"], "the rewrite would drop content markdown cannot hold; append instead, or narrow `--old`."],
  [["HELPER_NOT_RUNNING"], "Overnote is closed or its socket was refused; follow the hint (`overnote-axi open` to start it, or `overnote-axi status` to see why it was refused), then retry the write."],
  [["AMBIGUOUS_NOTE", "AMBIGUOUS_TEXT"], "pick a full id from the candidates, or add context to `--old`."],
  [["NOTE_TRASHED"], "the note is in Recently Deleted; recover it only if the user wants it back."],
  [["OUTCOME_UNKNOWN", "HELPER_TIMEOUT"], "the write may have landed (a `HELPER_TIMEOUT` on `create` or `duplicate` included); run `overnote-axi read <id>` (or `overnote-axi list --sort created` after `create` or `duplicate`) before any retry."],
] as const satisfies readonly (readonly [codes: readonly ErrorCode[], advice: string])[];

function errorLine([codes, advice]: (typeof ERRORS)[number]): string {
  return `${codes.map((code) => `\`${code}\``).join(" and ")}: ${advice}`;
}

function bullets(lines: readonly string[]): string[] {
  return lines.map((line) => `- ${line}`);
}

function sentence(text: string): string {
  return /[.!?]$/.test(text) ? text : `${text}.`;
}

/**
 * Every line says the bare `overnote-axi`; an installed copy states once, near the top, what it
 * stands for, so a long node plus script path is never repeated.
 */
export function buildSkill(input: SkillInput): string {
  const code = (text: string) => `\`${text}\``;
  const invocation =
    input.command === NAME
      ? [
          "If `command -v overnote-axi` fails, run `npm install -g .` in the overnote-axi repository, or run `node <overnote-axi repo>/dist/overnote-axi.js` wherever this skill says `overnote-axi`.",
        ]
      : [
          `This copy was installed by \`overnote-axi setup skill\`: wherever this skill says \`overnote-axi\`, run ${input.command} instead.`,
        ];
  const examples = EXAMPLES.flatMap(([comment, line]) => [...(comment ? [`# ${comment}`] : []), line]);

  return [
    "---",
    `name: ${SKILL_NAME}`,
    `description: ${JSON.stringify(SKILL_DESCRIPTION)}`,
    "---",
    "",
    SKILL_MARKER,
    "",
    "# Overnote notes with overnote-axi",
    "",
    "overnote-axi reads, searches, creates, updates, organizes, and links notes in Overnote, the floating notepad for Raycast.",
    "Output is compact TOON on stdout; reads work while Overnote is closed, and writes go through the running app.",
    ...invocation,
    "",
    "## Start here",
    "",
    `Run ${code("overnote-axi")} first: it shows the helper state, note counts, the current note, pinned and recent notes, and its next steps:`,
    "",
    ...bullets(input.homeHints.map(code)),
    "",
    "Then:",
    "",
    ...bullets(input.workflow.map(sentence)),
    "",
    "## Commands",
    "",
    "```text",
    input.commands,
    "```",
    "",
    sentence(input.noteRefs.replace(/^<note>/, "`<note>`").replace("title:<exact title>", "`title:<exact title>`")),
    "Every command takes `--help`, and flags go after the command.",
    "Exit codes: 0 success including no-ops, 1 error, 2 usage error; every error prints `code` and `help` lines.",
    "",
    "## Examples",
    "",
    "```sh",
    ...examples,
    "```",
    "",
    "Content goes in `--content <markdown>`, `--content -` (stdin), or `--content-file <path>`; use a file for anything longer than a line or two.",
    "",
    "## Supported markdown",
    "",
    ...bullets(MARKDOWN_SUBSET),
    "",
    "## Writing clean notes",
    "",
    "In a note the person wrote, follow its existing layout; these rules are for notes you create and maintain.",
    `They match [Overnote's guide](${FORMATTING_DOCS}).`,
    "",
    ...bullets(FORMATTING.map(sentence)),
    "",
    "## Safety rules",
    "",
    ...bullets(input.safety.map(sentence)),
    "",
    "## Common errors",
    "",
    ...bullets(ERRORS.map(errorLine)),
    "",
  ].join("\n");
}

export type SkillChange = "installed" | "updated" | "unchanged" | "removed" | "absent";

export function skillFile(home: string): string {
  return path.join(home, ".claude", "skills", SKILL_NAME, "SKILL.md");
}

function unmanagedSkill(): never {
  throw axiError(
    `~/.claude/skills/${SKILL_NAME}/SKILL.md exists and was not written by setup, so it is left alone; move it away, then run setup skill again`,
    "IO_ERROR",
  );
}

export function installSkill(home: string, content: string): { file: string; change: SkillChange } {
  const file = skillFile(home);
  const current = readIfExists(file);
  if (current === content) return { file, change: "unchanged" };
  if (current !== null && !current.includes(SKILL_MARKER)) unmanagedSkill();
  writeAtomic(file, content);
  return { file, change: current === null ? "installed" : "updated" };
}

export function uninstallSkill(home: string): { file: string; change: SkillChange } {
  const file = skillFile(home);
  const current = readIfExists(file);
  if (current === null) return { file, change: "absent" };
  if (!current.includes(SKILL_MARKER)) unmanagedSkill();
  removeFile(file);
  // The skill's own directory, then the skills directory setup created for it, when either is empty.
  removeDirIfEmpty(path.dirname(file));
  removeDirIfEmpty(path.dirname(path.dirname(file)));
  return { file, change: "removed" };
}
