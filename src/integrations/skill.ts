/**
 * The overnote-axi Agent Skill. See docs/DESIGN.md section 9.
 *
 * `buildSkill()` renders skills/overnote-axi/SKILL.md from the same static guidance the home
 * view and the help print (src/guidance.ts) plus the top-level command list, with live state
 * stripped, so the skill cannot drift. scripts/build-skill.mjs writes it; `--check` fails on a
 * stale copy.
 *
 * Invocation rule: the committed SKILL.md uses the bare `overnote-axi` and tells the agent that
 * when `command -v overnote-axi` fails it should run `npm install -g .` in this repository, or
 * use `node <repo>/dist/overnote-axi.js`. `setup skill` writes its installed copy with the
 * command hookCommand() resolves, stated exactly once near the top as what `overnote-axi` stands
 * for; every other line keeps the bare name, so a long node plus script path is never repeated.
 * No `npx` invocation may appear until the npm name is published and owned by this project (a
 * test enforces it).
 *
 * `setup skill` installs to `~/.claude/skills/overnote-axi/SKILL.md` only; other agents use
 * `npx skills add WesleyBLDC/overnote-axi --skill overnote-axi` (that runs the skills
 * installer, not this CLI).
 */
import path from "node:path";

import { axiError, type ErrorCode } from "../errors.js";
import { FORMATTING, FORMATTING_DOCS, HOME_HINTS, NOTE_REF_HELP, SAFETY, WORKFLOW } from "../guidance.js";
import { NAME } from "../meta.js";
import { COMMANDS } from "../registry.js";
import { readIfExists, removeDirIfEmpty, removeFile, writeAtomic } from "./files.js";

export const SKILL_NAME = "overnote-axi";

/** Marks a SKILL.md as generated, so setup never overwrites or removes one a person wrote. */
export const SKILL_MARKER =
  "<!-- Generated by overnote-axi from src/integrations/skill.ts; run npm run build:skill instead of editing this file. -->";

export const SKILL_DESCRIPTION =
  "Read, search, create, update, organize, and link Overnote notes (the Raycast floating notepad) from the command line. " +
  "Use when a task mentions Overnote, Raycast notes, a scratchpad or quick note, or reading, searching, appending to, " +
  "checking off, pinning, linking, or deleting a note.";

export interface SkillInput {
  /** What `overnote-axi` stands for: itself in the repo copy, hookCommand() in a copy setup installs. */
  command: string;
  /** The top-level help's commands block. */
  commands: string;
  noteRefs: string;
  homeHints: readonly string[];
  workflow: readonly string[];
  safety: readonly string[];
}

/** The top-level help's command list, one `name  summary` line per command. */
export function commandsBlock(): string {
  const width = Math.max(...COMMANDS.map((entry) => entry.name.length));
  return COMMANDS.map((entry) => `${entry.name.padEnd(width)}  ${entry.summary}`).join("\n");
}

/** The input for a skill that runs the CLI as `command`, from the CLI's own help and guidance. */
export function skillInput(command: string = NAME): SkillInput {
  return {
    command,
    commands: commandsBlock(),
    noteRefs: NOTE_REF_HELP,
    homeHints: HOME_HINTS,
    workflow: WORKFLOW,
    safety: SAFETY,
  };
}

/** The committed skills/overnote-axi/SKILL.md. */
export function repoSkill(): string {
  return buildSkill(skillInput(NAME));
}

