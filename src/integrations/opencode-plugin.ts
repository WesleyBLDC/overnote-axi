/**
 * Source of the managed OpenCode plugin. OpenCode loads every module in
 * `$XDG_CONFIG_HOME/opencode/plugins/`; this one runs the home view once per session, without a
 * shell, and adds its output to the system context, the OpenCode equivalent of a SessionStart
 * hook. A failure or a timeout adds nothing, so the plugin can never break a session. A call
 * without a session id (OpenCode also runs the transform for agent generations that are not
 * chat sessions) adds nothing either.
 */

export interface PluginSpec {
  /** First line of the file; marks it as managed by setup. */
  marker: string;
  /** The program and its leading arguments, for example `["overnote-axi"]`. */
  program: readonly string[];
  /** The home view arguments the hook runs. */
  args: readonly string[];
  timeoutSeconds: number;
}

export function openCodePluginSource(spec: PluginSpec): string {
  const argv = [...spec.program, ...spec.args];
  return [
    spec.marker,
    "// Adds the overnote-axi home view (Overnote helper state, pinned and recent notes) to each session's system context.",
    "// Regenerated by overnote-axi setup; local edits are replaced on the next install.",
    'import { spawn } from "node:child_process";',
    "",
    `const ARGV = ${JSON.stringify(argv)};`,
    `const TIMEOUT_MS = ${spec.timeoutSeconds * 1000};`,
    "",
    "function homeView() {",
    "  return new Promise((resolve) => {",
    '    let out = "";',
    "    let done = false;",
    "    let timer;",
    "    const finish = (text) => {",
    "      if (done) return;",
    "      done = true;",
    "      clearTimeout(timer);",
    "      resolve(text);",
    "    };",
    "    let child;",
    "    try {",
    '      child = spawn(ARGV[0], ARGV.slice(1), { stdio: ["ignore", "pipe", "ignore"], shell: false });',
    "    } catch {",
    '      finish("");',
    "      return;",
    "    }",
    "    timer = setTimeout(() => {",
    "      child.kill();",
    '      finish("");',
    "    }, TIMEOUT_MS);",
    '    child.stdout.setEncoding("utf8");',
    '    child.stdout.on("data", (chunk) => {',
    "      out += chunk;",
    "    });",
    '    child.on("error", () => finish(""));',
    '    child.on("close", () => finish(out.trim()));',
    "  });",
    "}",
    "",
    "export const OvernoteAxiPlugin = async () => {",
    "  const views = new Map();",
    "  return {",
    '    "experimental.chat.system.transform": async (input, output) => {',
    "      const session = input?.sessionID;",
    "      if (!session) return;",
    "      if (!views.has(session)) views.set(session, await homeView());",
    "      const view = views.get(session);",
    '      if (view) output.system.push("## Overnote notes (overnote-axi home)\\n" + view);',
    "    },",
    "  };",
    "};",
    "",
  ].join("\n");
}
