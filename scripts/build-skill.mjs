// Generates skills/overnote-axi/SKILL.md from buildSkill() in src/integrations/skill.ts, so the
// skill cannot drift from the CLI. `--check` fails when the committed file is stale.
//
// Owned by the integrations slice. Until it lands, generation is not available, and `--check`
// fails while the scaffold placeholder is still in the file, so `npm run check` cannot pass
// with an unfinished skill.
import { readFileSync } from "node:fs";
import path from "node:path";

import { repoRoot } from "./overnote-dir.mjs";

const PLACEHOLDER = "<!-- overnote-axi: placeholder, generated by scripts/build-skill.mjs -->";
const file = path.join(repoRoot, "skills", "overnote-axi", "SKILL.md");
const check = process.argv.includes("--check");

if (readFileSync(file, "utf8").includes(PLACEHOLDER)) {
  process.stderr.write(`build-skill: ${path.relative(repoRoot, file)} is still the scaffold placeholder (integrations slice)\n`);
  process.exit(check ? 1 : 0);
}
